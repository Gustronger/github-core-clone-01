/** A scenario user: the id, login, display name and email the checks use. */
export interface ScenarioUser {
  readonly id: number;
  readonly login: string;
  readonly name: string;
  readonly email: string;
}

/** `count` users with unique logins, deterministic for `rng`. */
export function generateUsers(rng: Rng, count: number): ScenarioUser[] {
  const used = new Set<string>();
  const users: ScenarioUser[] = [];
  for (let i = 0; i < Math.max(0, Math.trunc(count)); i += 1) {
    const first = rng.pick(FIRST_NAMES);
    const last = rng.pick(LAST_NAMES);
    const base = `${first}${last}`.replace(/[^a-z0-9-]/g, '');
    let login = base;
    let suffix = 2;
    while (used.has(login)) {
      login = `${base}-${suffix}`;
      suffix += 1;
    }
    used.add(login);
    users.push(Object.freeze({ id: 1000 + i, login, name: `${first} ${last}`, email: `${login}@example.invalid` }));
  }
  return users;
}

/**
 * The viewer: the first user of the scenario's 12, derived from the seed.
 * Verified against the kit's buildScenario(): login `adaiversen`, id 1000,
 * name "ada iversen", email adaiversen@example.invalid.
 */
export const VIEWER: ScenarioUser = generateUsers(scenarioRng('users'), 12)[0];

/** The viewer login every repository belongs to. */
export const VIEWER_LOGIN = VIEWER.login;

/** The identity line the entry signs its own commits with (viewer name + email). */
export const VIEWER_IDENTITY = `${VIEWER.name} <${VIEWER.email}>`;
